/*
 * W93 MIXXTUNE_COUNTRY_NAME_COLUMN
 * Store reports sometimes give the full country name ("South Africa") instead
 * of a 2-letter code. This turns the name into the ISO code for country_code.
 * Unknown values (for example "Z1 - WMISL") give null - nothing is guessed.
 */
final class CountryNames
{
    public static function code(?string $value): ?string
    {
        $v = trim((string) $value);
        if ($v === '') {
            return null;
        }
        if (preg_match('/^[A-Za-z]{2}$/', $v)) {
            return strtoupper($v);
        }
        $ascii = function_exists('iconv') ? (string) @iconv('UTF-8', 'ASCII//TRANSLIT', $v) : $v;
        $key = trim((string) preg_replace('/[^a-z0-9]+/', ' ', strtolower($ascii !== '' ? $ascii : $v)));

        return self::NAMES[$key] ?? null;
    }

